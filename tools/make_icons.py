def render(grid: str, color: tuple[int, int, int, int]) -> Image.Image:
    rows = [r for r in grid.strip().splitlines()]
    assert len(rows) == GRID, f"rows={len(rows)}"
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == GRID, f"row {y} len={len(row)}: {row!r}"
        for x, ch in enumerate(row):
            if ch == "#":
                for dy in range(CELL):
                    for dx in range(CELL):
                        px[x * CELL + dx, y * CELL + dy] = color
    return img


def data_uri(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, "PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def card_html(name: str, label: str, w_uri: str, b_uri: str) -> str:
    return f"""
    <div class="card">
      <h2>{name} <span class="label">{label}</span></h2>
      <div class="pair">
        <div class="sw dark"><img src="{w_uri}"></div>
        <div class="sw light"><img src="{b_uri}"></div>
      </div>
    </div>"""


