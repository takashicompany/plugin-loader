    here = pathlib.Path(__file__).resolve().parent
    outdir = here.parent / "loader" / "icons"
    outdir.mkdir(exist_ok=True)

    def build(icons):
        cards = []
        for name, label, grid in icons:
            white = render(grid, (255, 255, 255, 255))
            black = render(grid, (17, 17, 17, 255))
            white.save(outdir / f"{name}.png")
            cards.append(card_html(name, label, data_uri(white), data_uri(black)))
        return cards

